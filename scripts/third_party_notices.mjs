// Generate frontend/public/THIRD_PARTY_NOTICES.txt from the packages that the production build actually bundles,
// plus vendored code, the bundled font and imagery credits. Run from the repository root:
//   node scripts/third_party_notices.mjs
// It runs an in-memory Vite build (nothing is written to dist/) and reads each bundled package's own licence file.
import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fe = join(root, "frontend");
const req = createRequire(join(fe, "package.json"));
const { build } = await import(pathToFileURL(req.resolve("vite")).href);

const NUL = String.fromCharCode(0); // Rollup prefixes virtual module ids with this character
const pkgs = new Map(); // name -> package directory
const collector = {
  name: "collect-bundled-packages",
  generateBundle(_, bundle) {
    for (const chunk of Object.values(bundle)) {
      if (chunk.type !== "chunk") continue;
      for (const id of Object.keys(chunk.modules)) {
        const clean = (id.startsWith(NUL) ? id.slice(1) : id).split("?")[0].split("\\").join("/");
        const at = clean.lastIndexOf("/node_modules/");
        if (at < 0) continue;
        const rest = clean.slice(at + "/node_modules/".length).split("/");
        const name = rest[0].startsWith("@") ? `${rest[0]}/${rest[1]}` : rest[0];
        pkgs.set(name, `${clean.slice(0, at)}/node_modules/${name}`);
      }
    }
  },
};
await build({ root: fe, configFile: join(fe, "vite.config.ts"), logLevel: "error", plugins: [collector], build: { write: false } });

// Upstream licence texts for bundled packages that do not ship one (kept in frontend/licenses/).
const OVERRIDES = { "@react-three/fiber": "react-three-fiber.LICENSE", gsap: "gsap.NOTICE" };
const licenceFile = (dir, name) => {
  if (OVERRIDES[name]) return `${readFileSync(join(fe, "licenses", OVERRIDES[name]), "utf8").trim()}
(Vendored copy in frontend/licenses/; the npm package ships no licence file.)`;
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i.test(n));
  return f ? readFileSync(join(dir, f), "utf8").trim() : null;
};
const rule = "=".repeat(78);
const out = [
  "Azelux - third-party notices",
  "Generated by scripts/third_party_notices.mjs from the production frontend bundle.",
  "Azelux's own licence is not yet decided; this file covers third-party material only.",
  "",
];
const missing = [];
for (const name of [...pkgs.keys()].sort()) {
  const dir = pkgs.get(name);
  const pj = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const lic = typeof pj.license === "string" ? pj.license : JSON.stringify(pj.license ?? pj.licenses ?? "UNKNOWN");
  const text = licenceFile(dir, name);
  if (!text) missing.push(`${name}@${pj.version} (${lic})`);
  const home = pj.homepage || (pj.repository && (pj.repository.url || pj.repository)) || "";
  out.push(rule, `${name} ${pj.version} - ${lic}`, String(home), "", text || `No licence file is shipped in the package. Licence declared in package.json: ${lic}.`, "");
}
const vendored = [
  ["Schibsted Grotesk font (frontend/src/theme/fonts/SchibstedGrotesk.woff2)", join(fe, "src/theme/fonts/SchibstedGrotesk-OFL.txt")],
];
for (const [label, file] of vendored) out.push(rule, label, "", existsSync(file) ? readFileSync(file, "utf8").trim() : "LICENCE FILE MISSING", "");
out.push(rule, "Imagery and data credits", "");
out.push("- Moon texture: NASA Scientific Visualization Studio, CGI Moon Kit (SVS 4720), LRO Camera (LROC) colour mosaic. NASA imagery, public domain. https://svs.gsfc.nasa.gov/4720");
out.push("- Map basemaps (served by the backend): NASA LOLA / PGDA product 90 hillshade (Barker et al. 2023) and NASA SVS whole-Moon context; cited on the map when shown.");
out.push("- Computation data (server-side, not in this bundle): NAIF SPICE kernels (JPL), LOLA/PGDA DEMs and illumination maps (NASA GSFC); cited on the Methods page.");
out.push("");
mkdirSync(join(fe, "public"), { recursive: true });
writeFileSync(join(fe, "public", "THIRD_PARTY_NOTICES.txt"), out.join("\n"));
console.log(`bundled packages: ${pkgs.size}; without a licence file: ${missing.length ? missing.join(", ") : "none"}`);
console.log([...pkgs.keys()].sort().join(", "));
